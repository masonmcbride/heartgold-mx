#!/usr/bin/env python3
"""Compile-only ARM64 survey. Never links or executes any upstream game code.

Raw diagnostics and object files belong in an ignored build directory. This script
parses the explicit Meson file lists, not every C file in the checkout (tools and
ARM7 firmware are different targets). Uses only our explicit compatibility interfaces;
no placeholder SDK structs or success stubs are generated by this audit.
"""
import argparse
import collections
import concurrent.futures
import datetime
import hashlib
import json
import os
import pathlib
import re
import subprocess
import time


def manifest(root, relative, variable):
    path = root / relative
    text = re.sub(r'#.*', '', path.read_text())
    match = re.search(r'\b' + re.escape(variable) + r'\s*=\s*files\((.*?)\)', text, re.S)
    if not match:
        raise ValueError(f'Cannot locate {variable} in {relative}')
    result = []
    for name in re.findall(r"['\"]([^'\"]+\.(?:c|cpp|s))['\"]", match[1]):
        source = (path.parent / name).resolve()
        source.relative_to(root)
        if not source.is_file():
            raise ValueError(f'Missing source: {source}')
        result.append(source)
    if len(result) != len(set(result)):
        raise ValueError(f'Duplicate entries in {relative}')
    return result


def run(command, log, seconds=40, max_bytes=262144):
    """Bound assembler diagnostics too; Clang's C error limit doesn't cover them."""
    start = time.monotonic()
    reason = None
    with log.open('wb') as output:
        process = subprocess.Popen(command, stdout=output, stderr=subprocess.STDOUT)
        while process.poll() is None:
            if time.monotonic() - start > seconds:
                reason = 'time_budget'
            elif log.stat().st_size > max_bytes:
                reason = 'diagnostic_budget'
            if reason:
                process.kill()
                break
            time.sleep(0.05)
        code = process.wait()
    text = log.read_bytes()[:max_bytes].decode('utf-8', errors='replace')
    if log.stat().st_size > max_bytes:
        log.write_text(text + '\n[diagnostics truncated by audit]\n')
    return code, text, reason, round(time.monotonic() - start, 3)


def classify(text, reason):
    missing = re.search(r"fatal error: ['<]([^'>]+)['>] file not found", text)
    first = next((line.strip() for line in text.splitlines() if re.search(r'\b(?:fatal )?error:', line)), '')
    if missing:
        header = missing[1]
        sdk = header.startswith(('nitro', 'nnsys', 'dwc', 'vct', 'nitrowifi'))
        return ('missing_sdk_header' if sdk else 'missing_header'), header, first
    if 'unknown type name' in text or 'incomplete type' in text or 'incomplete definition' in text:
        return 'types_or_header_boundary', None, first
    if 'undeclared identifier' in text or 'undeclared function' in text:
        return 'missing_declaration_or_constant', None, first
    if any(s in text for s in ('unknown directive', 'invalid instruction', 'invalid operand', 'unrecognized instruction', 'unsupported directive')):
        return 'assembly_or_target', None, first
    return reason or ('compiler_error' if first else 'compiler_failure'), None, first


def symbols(path, undefined=False):
    command = ['xcrun', 'nm', '-u' if undefined else '-gU', str(path)]
    result = subprocess.run(command, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if result.returncode:
        return set()
    if undefined:
        return {line.strip().split()[-1] for line in result.stdout.splitlines() if line.strip() and not line.endswith(':')}
    return {match[1] for line in result.stdout.splitlines() if (match := re.search(r'\b[A-Z]\s+(\S+)$', line))}


def include_graph(root, sources, include_dirs):
    edges, missing, todo, visited = {}, {}, list(sources), set()
    def label(path):
        try:
            return path.relative_to(root).as_posix()
        except ValueError:
            return '@generated/' + path.name
    while todo:
        source = todo.pop()
        if source in visited:
            continue
        visited.add(source)
        names = re.findall(r'^\s*#\s*include\s*["<]([^">]+)[">]', source.read_text(errors='replace'), re.M)
        resolved, unresolved = [], []
        for name in names:
            found = next((p.resolve() for directory in [source.parent] + include_dirs if (p := directory / name).is_file()), None)
            if found:
                resolved.append(label(found))
                # Traverse only local upstream source/header files, never macOS SDK.
                if found.is_relative_to(root):
                    todo.append(found)
            else:
                unresolved.append(name)
        edges[label(source)] = sorted(set(resolved))
        if unresolved:
            missing[label(source)] = sorted(set(unresolved))
    return {'edges': edges, 'unresolved_literal_includes': missing,
            'note': 'Static include graph ignores preprocessor conditions. Unresolved includes may be system headers, not actual blockers; compiler diagnostics decide failures.'}


def write_report(data, path):
    lines = ['# Native compilation survey', '',
             f"Upstream revision: `{data['revision']}`. Compiler: `{data['compiler_version'].splitlines()[0]}`.", '',
             'This is a compile-only survey, not a full game executable or a port-completion percentage. Nothing produced by this audit is executed. Successful objects may still contain unsafe DS assumptions or unresolved calls.', '',
             '## Manifest scope', '', '| Group | C units | Assembly units |', '| --- | ---: | ---: |']
    for group, counts in data['scope'].items():
        lines.append(f"| {group} | {counts['c']} | {counts['asm']} |")
    lines += ['', 'The game lists come from `src/meson.build` and `asm/meson.build`. Support units come from explicit library manifests. External SDK implementations, host asset tools, ARM7 firmware, and the prebuilt DSProt archive are not compiled by this survey. The original build uses the DSProt archive; its available source manifest is listed separately, not substituted into the game build.', '',
              '## Compiler results', '', '| Pass | Attempted | Object files emitted | Failed/limited |', '| --- | ---: | ---: | ---: |']
    for mode in data['modes']:
        rows = [r for r in data['results'] if r['mode'] == mode]
        passed = sum(r['compiled'] for r in rows)
        lines.append(f'| {mode} | {len(rows)} | {passed} | {len(rows)-passed} |')
    lines += ['', '`unadapted` uses original headers. `compat` force-includes our current compatibility header, plus the field-specific header for the three field-library source files. Both use ARM64 Apple Clang, HeartGold/English configuration and current generated headers. `assembly` tries the ARM/Thumb sources with the ARM64 assembler; no ARM instruction translation is performed. Diagnostics are capped at 12 C errors per unit, 256 KiB per log, and 40 seconds per invocation; limited invocations are explicitly marked in JSON.', '',
              '## First blocking dependencies', '', '| Pass | Missing header | Units stopped here |', '| --- | --- | ---: |']
    for (mode, header), count in sorted(data['missing_headers'].items(), key=lambda x: -x[1]):
        lines.append(f'| {mode} | `{header}` | {count} |')
    lines += ['', 'These are visible first blockers, not a complete list of dependencies or the number of fixes required. One missing shared header can hide thousands of downstream errors.', '', '## Compatibility-pass object files', '']
    for row in data['results']:
        if row['mode'] == 'compat' and row['compiled']:
            lines.append(f"- `{row['source']}` ({row['group']})")
    lines += ['', '## Undefined references in successful compatibility objects', '',
              f"The objects reference {len(data['undefined_symbols'])} distinct symbols not defined by other successful objects or our current runtime library. Host system/library symbols are included; this is not a count of missing implementations. Symbols present in our runtime may still be aborting unsupported-entry-point stubs, so this is not service-completeness evidence.", '',
              '| Symbol | Referencing units | Possible provider |', '| --- | ---: | --- |']
    for item in data['undefined_symbols'][:50]:
        providers = ', '.join('`'+p+'`' for p in item['possible_providers'][:3]) or 'SDK / host / unindexed code'
        lines.append(f"| `{item['symbol']}` | {len(item['users'])} | {providers} |")
    lines += ['', 'Provider names are a static source-index hint, not link resolution. All symbol users/providers are in `summary.json`.', '',
              '## Full link status', '', 'Not attempted: complete game objects are unavailable and DS ARM/Thumb assembly cannot be linked into an ARM64 Mach-O application unchanged. Overlay loading, DS runtime services and SDK/static-library ABIs also require native replacements. Compiling individual objects does not establish linkability or runtime correctness.', '',
              '## Reproduction and raw evidence', '', 'Run `cmake --build build --target audit_native`. Detailed commands, exit codes, diagnostic limits, per-file logs, object paths, source hashes, static include graph and candidate symbol providers are in this ignored audit directory. The source hash comparison verifies that this audit did not change inspected upstream files. The existing executable test suite remains the measure of what actually runs natively.', '']
    path.write_text('\n'.join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--upstream', required=True, type=pathlib.Path)
    parser.add_argument('--generated', required=True, type=pathlib.Path)
    parser.add_argument('--output', required=True, type=pathlib.Path)
    parser.add_argument('--compiler', required=True)
    parser.add_argument('--runtime-library', type=pathlib.Path, action='append', default=[])
    parser.add_argument('--field-library', type=pathlib.Path)
    parser.add_argument('--jobs', type=int, default=4)
    args = parser.parse_args()
    root, generated, out = (p.resolve() for p in (args.upstream, args.generated, args.output))
    if out.is_relative_to(root) or out == root:
        parser.error('Audit output must be outside the unmodified upstream tree')
    out.mkdir(parents=True, exist_ok=True)
    project = pathlib.Path(__file__).resolve().parents[1]
    game_c = manifest(root, 'src/meson.build', 'pokeheartgold_c')
    game_asm = manifest(root, 'asm/meson.build', 'pokeheartgold_asm')
    support_c = manifest(root, 'lib/spl/meson.build', 'libspl_srcs')
    support_asm = manifest(root, 'lib/NitroDWC/asm/meson.build', 'nitrodwc_asm') + manifest(root, 'lib/NitroDWC/asm/meson.build', 'libcrypto_static_srcs') + manifest(root, 'lib/NitroDWC/meson.build', 'libdwcppwlobby_srcs') + [root/'lib/asm/libirc.s', root/'lib/syscall/asm/_secure_IPKE.s']
    dsprot_c = manifest(root, 'lib/dsprot/src/meson.build', 'libdsprot_src')
    groups = [('game', game_c, game_asm), ('support libraries', support_c, support_asm), ('DSProt source (not selected by original link)', dsprot_c, [])]
    c_units = [(group, p) for group, c, asm in groups for p in c]
    asm_units = [(group, p) for group, c, asm in groups for p in asm]
    inputs = sorted({p for _, p in c_units+asm_units} | {p for p in root.rglob('meson.build')})
    def hashes():
        return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}
    before = hashes()
    include_dirs = [root/'include', generated, generated/'files', root/'files', root/'src', root/'asm', root/'asm/include', root/'lib/include', root/'lib/asm/include', root/'lib/NitroDWC/asm/include', root/'lib/spl/include', root/'lib/dsprot/include', root/'lib/syscall', root]
    include_args = [argument for p in include_dirs for argument in ('-I', str(p))]
    sdk = subprocess.check_output(['xcrun', '--sdk', 'macosx', '--show-sdk-path'], text=True).strip()
    base = [args.compiler, '-arch', 'arm64', '-isysroot', sdk, '-DHEARTGOLD', '-DENGLISH', '-DSDK_ARM9', '-DPM_KEEP_ASSERTS', '-D_MSL_RESTRICT='] + include_args
    def compile_unit(mode, group, source):
        relative = source.relative_to(root)
        object_path = out/mode/relative.with_suffix('.o')
        object_path.parent.mkdir(parents=True, exist_ok=True)
        object_path.unlink(missing_ok=True)
        command = base[:]
        if mode == 'assembly':
            command += ['-x', 'assembler-with-cpp', '-DPM_ASM', '-DSDK_ASM']
            command += ['-Wa,-I'+str(p) for p in (root/'asm',root/'asm/include',root/'lib/asm/include',root/'lib/NitroDWC/asm/include',root/'lib/syscall/asm')]
        else:
            command += ['-std=gnu11', '-fsigned-char', '-ferror-limit=12', '-fno-color-diagnostics', '-Wno-unknown-pragmas', '-include', str(root/'include/config.h')]
            if mode == 'compat':
                command += ['-I', str(project/'src'), '-I', str(project/'src/compat/include'), '-include', str(project/'src/compat/native.h')]
                if relative.as_posix() in {'src/map_header.c','src/map_matrix.c','src/metatile_behavior.c'}:
                    command += ['-include', str(project/'src/compat/field.h')]
        command += ['-c', str(source), '-o', str(object_path)]
        log = object_path.with_suffix('.log')
        code, text, limited, elapsed = run(command, log)
        compiled = code == 0 and object_path.is_file() and not limited
        category, missing, first = ('compiled', None, '') if compiled else classify(text, limited)
        return {'mode': mode, 'group': group, 'source': relative.as_posix(), 'compiled': compiled, 'exit_code': code,
                'limited': limited, 'category': category, 'missing_header': missing,
                'first_error': first.replace(str(root)+'/', ''), 'seconds': elapsed,
                'object': str(object_path.relative_to(out)) if compiled else None,
                'log': str(log.relative_to(out)), 'command': command}
    results = []
    for mode, units in [('unadapted',c_units), ('compat',c_units), ('assembly',asm_units)]:
        print(f'{mode}: attempting {len(units)} units', flush=True)
        with concurrent.futures.ThreadPoolExecutor(max_workers=max(1,min(8,args.jobs))) as pool:
            futures = [pool.submit(compile_unit,mode,group,p) for group,p in units]
            for future in concurrent.futures.as_completed(futures):
                results.append(future.result())
                done = sum(r['mode']==mode for r in results)
                if done%50==0 or done==len(units):
                    passed = sum(r['mode']==mode and r['compiled'] for r in results)
                    print(f'  {done}/{len(units)}, {passed} objects emitted', flush=True)
    results.sort(key=lambda r:(r['mode'],r['group'],r['source']))
    successful = [r for r in results if r['mode']=='compat' and r['compiled']]
    defined, users = set(), collections.defaultdict(list)
    for library in args.runtime_library:
        if not library.is_file():
            parser.error(f'Missing runtime library: {library}')
        defined |= symbols(library)
    if args.field_library and args.field_library.is_file():
        defined |= symbols(args.field_library)
    for row in successful:
        defined |= symbols(out/row['object'])
        for symbol in symbols(out/row['object'], undefined=True):
            users[symbol].append(row['source'])
    providers = collections.defaultdict(list)
    for _, source in c_units:
        for name in re.findall(r'^\s*(?:[\w*]+\s+)+\**\s*([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{', source.read_text(errors='replace'), re.M):
            providers['_'+name].append(source.relative_to(root).as_posix())
    for _, source in asm_units:
        for name in re.findall(r'^\s*(?:thumb_func_start|arm_func_start)\s+(\w+)', source.read_text(errors='replace'), re.M):
            providers['_'+name].append(source.relative_to(root).as_posix())
    unresolved = [{'symbol':symbol,'users':sorted(set(source_users)),'possible_providers':sorted(set(providers[symbol]))} for symbol,source_users in users.items() if symbol not in defined]
    unresolved.sort(key=lambda item:(-len(item['users']),item['symbol']))
    headers = collections.Counter((r['mode'],r['missing_header']) for r in results if r['missing_header'])
    after = hashes()
    libraries = args.runtime_library + ([args.field_library] if args.field_library else [])
    data = {'revision':subprocess.check_output(['git','-C',str(root),'rev-parse','HEAD'],text=True).strip(),
            'provider_libraries': {str(p.resolve()): hashlib.sha256(p.read_bytes()).hexdigest() for p in libraries},
            'compiler_version':subprocess.check_output([args.compiler,'--version'],text=True),
            'created_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),
            'scope':{group:{'c':len(c),'asm':len(asm)} for group,c,asm in groups},
            'modes':['unadapted','compat','assembly'],'results':results,'undefined_symbols':unresolved,
            'source_hashes':before,'upstream_inputs_unchanged':before==after,
            'missing_headers':headers}
    write_report(data,out/'REPORT.md')
    data['missing_headers']=[{'mode':mode,'header':header,'units':count} for (mode,header),count in headers.most_common()]
    (out/'summary.json').write_text(json.dumps(data,indent=2)+'\n')
    (out/'include_graph.json').write_text(json.dumps(include_graph(root,[p for _,p in c_units],include_dirs+[project/'src',project/'src/compat/include']),indent=2)+'\n')
    print(f'Report: {out / "REPORT.md"}',flush=True)
    print(f'Upstream inspected inputs unchanged: {before==after}',flush=True)
    # Compilation failures are findings, not a failed audit. Tool errors/hash changes fail.
    return 0 if before==after else 1

if __name__ == '__main__':
    raise SystemExit(main())
