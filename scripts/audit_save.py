#!/usr/bin/env python3
"""Inventory upstream save records against the explicit native story owner.

This reports source ownership, not linked functions, initialization correctness,
ABI compatibility, save/load coverage, or executable gameplay.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OWNED = {
    'SAVE_SYSINFO': ('sys_info', 'owned; initializer incomplete'),
    'SAVE_PLAYERDATA': ('profile', 'partial: profile/options; coins and IGT absent'),
    'SAVE_PARTY': ('party', 'owned'), 'SAVE_BAG': ('bag', 'owned'),
    'SAVE_FLAGS': ('vars', 'owned'),
    'SAVE_LOCAL_FIELD_DATA': ('blackout_spawn', 'partial: blackout spawn only'),
    'SAVE_POKEDEX': ('dex', 'owned'),
    'SAVE_MISC': ('misc', 'owned; initializer incomplete'),
    'SAVE_GAMESTATS': ('stats', 'owned'), 'SAVE_POKEGEAR': ('pokegear', 'owned'),
}

def tables(source):
    result = []
    for name in ('gSaveChunkHeaders', 'gExtraSaveChunkHeaders'):
        matches = re.findall(r'\b' + name + r'\[\]\s*=\s*\{(.*?)\n\};', source, re.S)
        if len(matches) != 1:
            raise ValueError(f'ambiguous/missing table {name}')
        body = matches[0]
        entries = re.findall(r'\{([^{}]*)\}', body)
        if re.sub(r'[\s,]', '', re.sub(r'\{[^{}]*\}', '', body)):
            raise ValueError(f'unparsed content in {name}')
        rows = []
        for entry in entries:
            fields = [x.strip() for x in entry.split(',') if x.strip()]
            if len(fields) != 4:
                raise ValueError(f'invalid record: {entry}')
            fields[2] = re.sub(r'^\(SAVESIZEFN\)\s*', '', fields[2])
            fields[3] = re.sub(r'^\(SAVEINITFN\)\s*', '', fields[3])
            if not all(re.fullmatch(r'[A-Za-z_]\w*', x) for x in fields[2:]):
                raise ValueError(f'invalid callbacks: {fields}')
            rows.append(fields)
        if len({x[0] for x in rows}) != len(rows):
            raise ValueError(f'duplicate IDs in {name}')
        result.append(rows)
    return result

def report():
    upstream = ROOT / 'upstream/pokeheartgold'
    normal, extra = tables((upstream / 'src/save_arrays.c').read_text())
    constants = dict(re.findall(r'^#define\s+(SAVE_\w+)\s+(\d+)\s*$', (upstream / 'include/constants/save_arrays.h').read_text(), re.M))
    if len(normal) != int(constants['SAVE_BLOCK_NUM']):
        raise ValueError('normal table/count mismatch')
    if {int(constants[r[0]]) for r in normal} != set(range(len(normal))):
        raise ValueError('normal IDs are not complete/contiguous')
    owner = (ROOT / 'src/field_script.c').read_text()
    story = re.findall(r'typedef struct\s*\{([^{}]*)\}\s*StoryData;', owner, re.S)
    if len(story) != 1:
        raise ValueError('StoryData changed; update ownership assessment')
    canonical = bool(re.search(r'\bSaveData\s+save\s*;', story[0]))
    if not canonical:
        for key, (field, _) in OWNED.items():
            if not re.search(r'\b' + field + r'\b', story[0]):
                raise ValueError(f'{key}: expected owned field {field} missing')
    # Index C and assembly definitions in one pass; declarations do not count.
    definitions = {}
    pattern = re.compile(r'^\s*(?:[\w*]+[ \t]+)*([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{|^([A-Za-z_]\w*):', re.M)
    for directory in ('src', 'asm'):
        for path in sorted((upstream / directory).rglob('*')):
            if path.suffix not in ('.c', '.s'):
                continue
            for match in pattern.finditer(path.read_text(errors='replace')):
                symbol = match[1] or match[2]
                definitions.setdefault(symbol, []).append(str(path.relative_to(upstream)))
    def location(symbol):
        paths = sorted(set(definitions.get(symbol, [])))
        return ', '.join(f'`{p}`' for p in paths) or 'not found by source index'
    lines = ['# Original save-record inventory', '',
             'Generated by `python3 scripts/audit_save.py --write`. Source inventory only; ownership does not establish initialization, linking, ABI compatibility or persistence.', '',
             f'The original tables declare **{len(normal)} normal records and {len(extra)} extra records**. ' + ('StoryData now embeds the original SaveData directory and all 42 normal records. Six extras use the original separate disk lifecycle. Initialization, retention and resume evidence are tracked in save-acceptance.md; source wiring alone does not close the complete-save gate.' if canonical else 'The selective owner contains eight whole record shapes and two partial records; other records are absent.'), '',
             '| ID | Original record | Page/block | Size callback | Initializer (definition) | Native ownership |',
             '|---|---|---|---|---|---|']
    for ident, page, size, init in normal:
        status = 'original table-owned record' if canonical else OWNED.get(ident, ('', 'absent'))[1]
        lines.append(f'| {constants[ident]} | `{ident}` | {page} | `{size}` | `{init}` ({location(init)}) | {status} |')
    lines += ['', '| Extra ID | Original page | Size callback | Initializer (definition) | Native ownership |', '|---|---|---|---|---|']
    for ident, page, size, init in extra:
        status = 'original separate manager APIs' if canonical else 'absent'
        lines.append(f'| {ident} | `{page}` | `{size}` | `{init}` ({location(init)}) | {status} |')
    if canonical:
        lines += ['', '## Integration boundaries', '',
                  '- Original SaveData and its complete normal-record directory replace selective record ownership. Original C initializers and assembly callbacks supply all registry entries; native SDK services are explicit compatibility boundaries.',
                  '- Complete PLAYERDATA includes coins and IGT. Full LocalFieldData is synchronized from the live transition owner at save preparation. The original saved-object exporter runs before publication; the native resource boundary reconstructs original serialized object fields on Continue.',
                  '- Temporary script flags and RNG remain native continuation state. Ordinary cartridge Continue clears temporary flags and reseeds runtime RNG; development checkpoints separately preserve these inspection-session fields.',
                  '- Original normal saves use a 512 KiB flash image with original slots/CRC/counters. Extra records retain their original lazy creation, mirrored and journaled APIs; they are not fabricated as always-present normal records.',
                  '- The native manager layout matches measured ARM constants. Complete per-record ABI comparisons, exhaustive interrupted-write/extra-journal recovery, original console/RTC ownership handling and broader field reconstruction remain acceptance obligations.',
                  '- Save/Continue, full-storage and corruption checks are documented in save-acceptance.md. This inventory is not a claim that every producer, menu, timed event or later-map resume path is implemented.', '']
    else:
        lines += ['', 'Selective snapshots are development state, not complete original saves.', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='update docs/save-inventory.md')
    mode.add_argument('--check', action='store_true', help='reject a stale inventory report')
    args = parser.parse_args()
    result = report()
    if args.write:
        (ROOT / 'docs/save-inventory.md').write_text(result)
        print('Wrote docs/save-inventory.md (42 normal + 6 extra records).')
    elif args.check:
        if (ROOT / 'docs/save-inventory.md').read_text() != result:
            parser.exit(1, 'Save inventory is stale; run scripts/audit_save.py --write.\n')
        print('Save inventory matches the original tables and current ownership assessment.')
    else:
        sys.stdout.write(result)
